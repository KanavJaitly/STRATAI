"""P8-M1 (P8-Q2): generate the frontend's API types from the live OpenAPI document.

    python -m scripts.phase8_generate_api_types          # write frontend/src/api/generated.ts
    python -m scripts.phase8_generate_api_types --check  # exit 1 if the file is out of date

The Phase 7 contract lock is defined over this same OpenAPI document (docs/api_contract_lock.json), so these types
are derived from the locked contract with no hand-copied shapes. `tests/test_phase8_frontend_types.py` fails when
the file is stale. Regenerate it after any API change, including description-only ones, because the field
descriptions are carried into the TypeScript as doc comments.

Mapping (JSON Schema → TypeScript):
- string → string (an enum or const → a union of string literals); integer and number → number; boolean →
  boolean; null → null;
- arrays → T[] (prefixItems → a tuple); an object with properties → an interface (a field not in `required` is
  optional); additionalProperties → Record<string, T>; a free object → Record<string, unknown>;
- anyOf / oneOf → a union; $ref → the component name.

No npm dependency is used, and the output is deterministic (sorted).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "frontend" / "src" / "api" / "generated.ts"
HEADER = """// GENERATED by scripts/phase8_generate_api_types.py from the API's OpenAPI document. DO NOT EDIT.
// Regenerate with `python -m scripts.phase8_generate_api_types`; tests/test_phase8_frontend_types.py fails on drift.
// These are the shapes the Phase 7 contract lock pins (docs/api_contract_lock.json).
/* eslint-disable */
"""
_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
_REF = "#/components/schemas/"


def openapi_document() -> dict[str, Any]:
    from api import create_app
    from data.config import Settings

    return create_app(Settings(api_prefix="")).openapi()


def _literal(value: Any) -> str:
    return json.dumps(value)


def ts_type(schema: dict[str, Any]) -> str:
    """The TypeScript type for one JSON-schema node."""
    if "$ref" in schema:
        return schema["$ref"].removeprefix(_REF)
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        return " | ".join(_literal(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts: list[str] = []
            for option in schema[key]:
                rendered = ts_type(option)
                if rendered not in parts:
                    parts.append(rendered)
            return " | ".join(parts)
    if "allOf" in schema:
        return " & ".join(ts_type(option) for option in schema["allOf"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts_type({**schema, "type": k}) for k in kind)
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts_type(item) for item in schema["prefixItems"]) + "]"
        item = ts_type(schema.get("items", {}))
        return f"({item})[]" if "|" in item or "&" in item else f"{item}[]"
    if kind == "object" or "properties" in schema:
        if schema.get("properties"):
            return _inline_object(schema)
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"Record<string, {ts_type(extra)}>"
        return "Record<string, unknown>"
    return "unknown"


def _doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    clean = " ".join(text.split()).replace("*/", "* /")
    return [f"{indent}/** {clean} */"]


def _fields(schema: dict[str, Any], indent: str) -> list[str]:
    required = set(schema.get("required", []))
    lines: list[str] = []
    for name in sorted(schema.get("properties", {})):
        prop = schema["properties"][name]
        key = name if _IDENT.match(name) else _literal(name)
        lines += _doc(prop.get("description"), indent)
        lines.append(f"{indent}{key}{'' if name in required else '?'}: {ts_type(prop)}")
    return lines


def _inline_object(schema: dict[str, Any]) -> str:
    return "{ " + "; ".join(line.strip() for line in _fields(schema, "") if not line.strip().startswith("/**")) + " }"


def render(document: dict[str, Any]) -> str:
    schemas = document.get("components", {}).get("schemas", {})
    out = [HEADER]
    for name in sorted(schemas):
        schema = schemas[name]
        out += _doc(schema.get("description"), "")
        if schema.get("type") == "object" and schema.get("properties"):
            out.append(f"export interface {name} {{")
            out += _fields(schema, "  ")
            out.append("}")
        else:
            out.append(f"export type {name} = {ts_type(schema)}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the generated file is out of date")
    args = parser.parse_args(argv)
    text = render(openapi_document())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date: run python -m scripts.phase8_generate_api_types",
                  file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
